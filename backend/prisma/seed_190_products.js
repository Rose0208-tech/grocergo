function generateSlug(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)+/g, '');
}

async function seed() {
  console.log('--- Starting GrocerGo 19 Categories & 190 Accurate AI Products Seeding ---');

  // Clean old cart items, order items, etc. to avoid foreign key conflicts
  await prisma.cartItem.deleteMany({});
  await prisma.inventoryMovement.deleteMany({});
  await prisma.orderItem.deleteMany({});
  await prisma.paymentProof.deleteMany({});
  await prisma.orderStatusHistory.deleteMany({});
  await prisma.order.deleteMany({});
  await prisma.productTranslation.deleteMany({});
  await prisma.product.deleteMany({});
  await prisma.categoryTranslation.deleteMany({});
  await prisma.category.deleteMany({});

  console.log('Cleaned previous category & product records.');

  let totalProductsCount = 0;

  for (const catData of categoriesData) {
    const category = await prisma.category.create({
      data: {
        name: catData.name,
        slug: catData.slug,
        description: catData.description,
        imageUrl: catData.imageUrl,
        sortOrder: catData.sortOrder,
        isActive: true
      }
    });

    // Add category translations
    for (const [lang, trans] of Object.entries(catData.translations || {})) {
      await prisma.categoryTranslation.create({
        data: {
          categoryId: category.id,
          language: lang,
          name: trans.name,
          description: trans.description
        }
      });
    }

    // Add 10 products
    for (const prodData of catData.products) {
      const prodSlug = generateSlug(prodData.name) + '-' + prodData.sku.toLowerCase();
      await prisma.product.create({
        data: {
          sku: prodData.sku,
          name: prodData.name,
          slug: prodSlug,
          description: prodData.description,
          categoryId: category.id,
          price: prodData.price,
          originalPrice: prodData.originalPrice,
          discountPercent: prodData.discountPercent || 0,
          unit: prodData.unit,
          packSize: prodData.packSize,
          stock: prodData.stock,
          imageUrl: prodData.imageUrl,
          isFeatured: Boolean(prodData.isFeatured),
          isActive: true
        }
      });
      totalProductsCount++;
    }

    console.log(`✓ Seeded category "${catData.name}" (${catData.slug}) with ${catData.products.length} products.`);
  }

  console.log(`\n🎉 Successfully seeded ${categoriesData.length} categories and ${totalProductsCount} total products!`);
}

seed()
  .catch((e) => {
    console.error('Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
