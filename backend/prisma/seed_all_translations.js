async function main() {
  console.log('Starting full translation seeding for 192 products...');

  const products = await prisma.product.findMany();
  console.log(`Found ${products.length} products in DB.`);

  let totalUpserted = 0;

  for (const prod of products) {
    const trans = productTranslations[prod.sku];
    if (!trans) {
      console.warn(`No translations defined for SKU: ${prod.sku} (${prod.name})`);
      continue;
    }

    const languages = ['ta', 'hi', 'te', 'kn', 'ml'];
    for (const lang of languages) {
      const entry = trans[lang];
      if (!entry) continue;

      const name = typeof entry === 'string' ? entry : entry.name;
      const description = typeof entry === 'string'
        ? `${name} - GrocerGo கிராமிய நேரடி புதிய தரம்.`
        : (entry.description || `${name} - GrocerGo Farm Fresh.`);

      await prisma.productTranslation.upsert({
        where: {
          productId_language: {
            productId: prod.id,
            language: lang
          }
        },
        update: {
          name,
          description
        },
        create: {
          productId: prod.id,
          language: lang,
          name,
          description
        }
      });
      totalUpserted++;
    }
  }

  console.log(`Successfully upserted ${totalUpserted} translation records!`);
  const finalCount = await prisma.productTranslation.count();
  console.log(`Total ProductTranslation records now in DB: ${finalCount}`);
}

main()
  .catch((e) => {
    console.error('Error seeding translations:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
